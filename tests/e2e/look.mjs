// Walks through the app and saves a screenshot of every screen, for looking at by eye.
// usage: node tests/e2e/look.mjs <outDir> [width] [height]
import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { serve } from '../../tools/serve.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const out = path.resolve(process.argv[2] || 'shots');
const width = Number(process.argv[3]) || 390;
const height = Number(process.argv[4]) || 844;
fs.mkdirSync(out, { recursive: true });

const { server, url } = await serve(path.join(root, 'dist'));
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width, height }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
let n = 0;
const shot = async (name) => {
  await page.waitForTimeout(150);
  await page.screenshot({ path: path.join(out, `${String(++n).padStart(2, '0')}-${name}.png`) });
};
const tap = (text, opts) => page.getByRole('button', { name: text, ...opts }).first().click();
const keys = async (s) => {
  for (const ch of s) await page.locator('.keypad .key', { hasText: new RegExp(`^${ch === '.' ? '\\.' : ch}$`) }).click();
};

await page.goto(url);
await page.waitForSelector('.tile');
await shot('home-ashirvad');
await tap('Supreme');
await shot('home-supreme');
await page.locator('.tile', { hasText: 'Elbow' }).first().click();
await shot('item-empty');
await page.locator('.size', { hasText: /^¾"/ }).first().click();
await keys('20');
await shot('item-qty');
await page.locator('.field[data-field=disc]').click();
await keys('42.5');
await shot('item-discount');
await tap('Add to bill');
await shot('home-after-add');
await page.locator('.tile', { hasText: 'Tee' }).first().click();
await page.locator('.size', { hasText: /^1"₹/ }).first().click();
await keys('10');
await shot('item-second');
await tap('Add to bill');
await tap('Brass', { exact: true });
await shot('home-brass');
await page.locator('.tile', { hasText: 'Tee' }).first().click();
await page.locator('.size', { hasText: /^¾"₹/ }).first().click();
await keys('6');
await page.locator('.field[data-field=disc]').click();
await keys('25');
await tap('Add to bill');
await tap('Ashirvad');
await tap('Pipe', { exact: true });
await shot('home-pipe');
await page.locator('.tile').first().click();
await page.locator('.size', { hasText: /^1"₹/ }).first().click();
await keys('5');
await page.locator('.field[data-field=disc]').click();
await keys('30');
await tap('Add to bill');
await tap('Plain', { exact: true });
await page.locator('.tile', { hasText: 'Socket' }).first().click();
await page.locator('.size', { hasText: /^1" × ¾"/ }).first().click();
await keys('6');
await page.locator('.field[data-field=disc]').click();
await keys('35');
await tap('Add to bill');
await tap('Brass', { exact: true });
await page.locator('.tile', { hasText: 'FTA' }).first().click();
await page.locator('.size', { hasText: /^¾"₹/ }).first().click();
await keys('2');
await page.locator('.field[data-field=disc]').click();
await keys('20');
await tap('Add to bill');
await tap('View bill');
await shot('bill-top');
await page.screenshot({ path: path.join(out, `${String(++n).padStart(2, '0')}-bill-full.png`), fullPage: true });
await page.locator('.chip', { hasText: 'Plain 42.5%' }).click();
await shot('discount-sheet');
await page.locator('.round-btn').click();
await page.locator('.line', { hasText: 'Tee 1"' }).click();
await shot('edit-line');
await page.locator('.round-btn').click();
await page.fill('#cust', 'Ramesh Kumar');
await tap('Finish bill');
await shot('gst');
await page.locator('.choice', { hasText: 'With GST' }).first().click();
await shot('done');
await page.screenshot({ path: path.join(out, `${String(++n).padStart(2, '0')}-done-full.png`), fullPage: true });
await tap('Start a new bill');
await shot('home-new');
await tap('Old bills');
await shot('old-bills');
await page.locator('.old-row').first().click();
await shot('old-view');
await page.goBack();
await page.goBack();
await page.locator('.rates-link').click();
await shot('rates');
console.log('errors:', errors.length ? errors : 'none');
await browser.close();
server.close();
